.section .text
.globl _start

_start:

    li x31,0


    # =================================================
    # mscratch = 0
    # =================================================

    csrrwi x0,0x340,0


    # =================================================
    # CSRRW
    # =================================================

    li x5,0x12345678

    csrrw x6,0x340,x5

    # EXPECT:
    # x6 = 0

    bne x6,x0,fail

    csrr x7,0x340

    li x8,0x12345678

    bne x7,x8,fail


    # =================================================
    # CSRRS
    # =================================================

    li x5,0x0000000f

    csrrs x6,0x340,x5

    # EXPECT x6 = 0x12345678

    li x7,0x12345678
    bne x6,x7,fail

    csrr x8,0x340

    li x9,0x1234567f

    bne x8,x9,fail


    # =================================================
    # CSRRC
    # =================================================

    li x5,0x0000000c

    csrrc x6,0x340,x5

    li x7,0x1234567f
    bne x6,x7,fail

    csrr x8,0x340

    li x9,0x12345673

    bne x8,x9,fail


    # =================================================
    # CSRRWI
    # =================================================

    csrrwi x10,0x340,21

    li x11,0x12345673
    bne x10,x11,fail

    csrr x12,0x340

    li x13,21
    bne x12,x13,fail


    # =================================================
    # CSRRSI
    # =================================================

    csrrsi x14,0x340,10

    li x15,21
    bne x14,x15,fail

    csrr x16,0x340

    li x17,31
    bne x16,x17,fail


    # =================================================
    # CSRRCI
    # =================================================

    csrrci x18,0x340,3

    li x19,31
    bne x18,x19,fail

    csrr x20,0x340

    li x21,28
    bne x20,x21,fail


pass:

    li x31,1

pass_loop:
    jal x0,pass_loop


fail:

    li x31,0

fail_loop:
    jal x0,fail_loop