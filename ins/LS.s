.section .text
.globl _start

_start:

    li x10,0x80000000


    # =================================================
    # SW / LW
    # =================================================

    li x5,0x12345678
    sw x5,0(x10)

    lw x6,0(x10)

    # EXPECT:
    # x5 = 0x12345678
    # x6 = 0x12345678


    # =================================================
    # SH / LHU
    # =================================================

    li x5,0x00005678
    sh x5,4(x10)

    lhu x6,4(x10)

    # EXPECT:
    # x6 = 0x00005678


    # =================================================
    # SB / LBU
    # =================================================

    li x5,0x0000007f
    sb x5,8(x10)

    lbu x6,8(x10)

    # EXPECT:
    # x6 = 0x0000007f


    # =================================================
    # LH signed extension
    # =================================================

    li x5,-2
    sh x5,12(x10)

    lh x6,12(x10)

    # EXPECT:
    # x6 = 0xfffffffe


    # =================================================
    # LB signed extension
    # =================================================

    li x5,-1
    sb x5,16(x10)

    lb x6,16(x10)

    # EXPECT:
    # x6 = 0xffffffff


    # =================================================
    # 多字节混合
    # =================================================

    li x5,0xaabbccdd
    sw x5,20(x10)

    lb  x6,20(x10)
    # EXPECT: x6 = 0xffffffdd

    lbu x7,21(x10)
    # EXPECT: x7 = 0x000000cc

    lh  x8,20(x10)
    # EXPECT: x8 = 0xffffccdd

    lhu x9,22(x10)
    # EXPECT: x9 = 0x0000aabb


    # 最后检查：
    # x5 = aabbccdd
    # x6 = ffffffdd
    # x7 = 000000cc
    # x8 = ffffccdd
    # x9 = 0000aabb