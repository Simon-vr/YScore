.section .text
.globl _start

_start:

    li x31,0


    # =================================================
    # LUI
    # =================================================

    lui x5,0x12345

    li x6,0x12345000

    bne x5,x6,fail


    # =================================================
    # AUIPC
    # =================================================

    auipc x7,0

    addi x8,x7,0

    bne x7,x8,fail


    # =================================================
    # JAL
    # =================================================

    jal x5,jal_target

    jal x0,fail


jal_target:

    # x5 应该保存返回地址
    # 这里只检查它非零
    beq x5,x0,fail


    # =================================================
    # JALR
    # =================================================

    la x6,jalr_return

    jalr x0,x6,0


    jal x0,fail


jalr_return:


    # =================================================
    # 普通指令穿插
    # =================================================

    li x9,100
    li x10,40

    sub x11,x9,x10

    li x12,60

    bne x11,x12,fail


pass:

    li x31,1

loop:
    jal x0,loop


fail:

    li x31,0

fail_loop:
    jal x0,fail_loop