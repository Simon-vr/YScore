.section .text
.globl _start

_start:

    # ------------------------------------------------
    # ADDI
    # ------------------------------------------------
    addi x1,x0,10
    addi x2,x1,5
    # EXPECT: x2 = 15


    # ------------------------------------------------
    # SLTI
    # ------------------------------------------------
    slti x3,x2,20
    # EXPECT: x3 = 1


    # ------------------------------------------------
    # SLTIU
    # ------------------------------------------------
    sltiu x4,x2,20
    # EXPECT: x4 = 1


    # ------------------------------------------------
    # XORI
    # ------------------------------------------------
    li x5,0x55
    xori x6,x5,0x0f
    # EXPECT: x6 = 0x5a


    # ------------------------------------------------
    # ORI
    # ------------------------------------------------
    ori x7,x5,0x0f
    # EXPECT: x7 = 0x5f


    # ------------------------------------------------
    # ANDI
    # ------------------------------------------------
    andi x8,x7,0x0f
    # EXPECT: x8 = 0x0f


    # ------------------------------------------------
    # SLLI
    # ------------------------------------------------
    li x9,1
    slli x10,x9,5
    # EXPECT: x10 = 32


    # ------------------------------------------------
    # SRLI
    # ------------------------------------------------
    li x11,32
    srli x12,x11,3
    # EXPECT: x12 = 4


    # ------------------------------------------------
    # SRAI
    # ------------------------------------------------
    li x13,-32
    srai x14,x13,3
    # EXPECT: x14 = -4


    # =================================================
    # R type
    # =================================================

    # ADD
    add x15,x1,x2
    # EXPECT: 25


    # SUB
    sub x16,x2,x1
    # EXPECT: 5


    # SLL
    li x17,1
    li x18,4
    sll x19,x17,x18
    # EXPECT: 16


    # SLT
    li x20,-1
    li x21,1
    slt x22,x20,x21
    # EXPECT: 1


    # SLTU
    sltu x23,x20,x21
    # EXPECT: 0


    # XOR
    xor x24,x5,x7
    # EXPECT: 0x0a


    # SRL
    li x25,32
    li x26,3
    srl x27,x25,x26
    # EXPECT: 4


    # SRA
    li x28,-32
    sra x29,x28,x26
    # EXPECT: -4


    # OR
    or x30,x5,x7
    # EXPECT: 0x5f


    # AND
    and x31,x5,x7
    # EXPECT: 0x55


    # 最终：
    # x31 = 0x55