`timescale 1ns / 1ps

module tb_core;

//============================================================================
// 时钟与复位
//============================================================================
reg clk;
reg rst;

// 时钟生成: 10ns 周期 (100MHz)
always #5 clk = ~clk;

//============================================================================
// 顶层接口
//============================================================================
wire uart_tx;
wire [3:0] gpio;
assign uart_rx = 1'b1;

//============================================================================
// DUT
//============================================================================
core_ctl u_core_ctl (
    .clk(clk),
    .rst(rst),
    .uart_rx(uart_rx),
    .uart_tx(uart_tx),
    .gpio(gpio)
);

//============================================================================
// 波形观察 —— 层次化路径访问 core_ctl 内部信号
//============================================================================
wire        wb_token      = u_core_ctl.wb_token;
wire        ifid_token    = u_core_ctl.ifid_token;
wire        exe_token     = u_core_ctl.exe_token;
wire        perips_token  = u_core_ctl.perips_token;

wire [31:0] wb_pc         = u_core_ctl.wb_pc;
wire [31:0] ifid_alusrc   = u_core_ctl.ifid_alusrc2;
wire [31:0] exe_alures    = u_core_ctl.exe_alures;
wire [31:0] perips_data   = u_core_ctl.perips_data;

//============================================================================
// 初始化
//============================================================================
initial begin
    clk = 0;
    rst = 1'b0;
    #20;
    rst = 1'b1;
end

//============================================================================
// 测试序列: 等待多条指令流经流水线
//============================================================================
initial begin
    // 等待复位释放后运行足够周期，让流水线填满并流过
    // 每个指令吃 5 周期 (if→ifid→exe→perips→wb)
    // mem_test.mem 有 ~20 条指令，5×20 = 100 周期，加 margin 跑 200 周期
    // exe_token 边沿监控
    wait(rst == 1'b1);
    repeat (200) @(posedge clk);
    $finish;
end

endmodule